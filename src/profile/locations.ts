/**
 * Словарь географических тегов — тегов, которые для Bandcamp есть просто имя
 * места (город/регион/страна артиста), а не жанровый или вкусовой маркер.
 * `buildProfile` (`./build.ts`) вычитает такие теги из весов бакета: живой
 * прогон 2026-08 показал 'new york' весом 1 в hardcore-punk (буквально
 * максимум шкалы, выше всех жанровых тегов) — город статистически
 * перепредставлен в коллекции (сцена NYHC там реально большая), но это
 * география коллекции, а не вкус, и релиз не должен получать очки просто за
 * то, что группа из Нью-Йорка.
 *
 * Отличить место от жанрового слова по обычному словарю английского нельзя:
 * 'portland' — только место, но 'bath', 'nice', 'reading' — это ОДНОВРЕМЕННО
 * реальные места и обычные английские слова, а в этом домене конкретно
 * 'richmond' — настоящий город (сцена краста/хардкора Ричмонда, Вирджиния),
 * тогда как 'hardcore' — жанровое слово и никогда не место. Общий
 * geo-словарь тут не помогает и не нужен: вместо него словарь строится из
 * данных, которые Bandcamp САМ размечает как место группы — поле
 * `band_location` в ответах Discover (см. `../bandcamp/discover.ts`). Всё,
 * что туда попало, по построению реальное место (это отдельное
 * структурированное поле профиля группы, а не свободный тег), так что
 * словарь не гадает по форме слова, а фиксирует то, что Bandcamp уже сам
 * разметил как гео — ровно то, о чём просили: разделение статистическое
 * совпадение (город коррелирует со сценой) не решает, а вот структурное
 * (это поле значит «место», а не «жанр») решает однозначно.
 */

export interface LocationSample {
  /** `band_location` результата Discover как есть — может быть null/пусто. */
  location: string | null;
  /**
   * Имя исполнителя того же результата. Нужно для дедупа: один разговорчивый
   * (или шутливый) артист, чей `band_location` случайно совпал бы с жанровым
   * словом, не должен в одиночку продавить его в словарь мест — см.
   * `buildLocationVocabulary`.
   */
  artist: string;
}

export interface LocationVocabularyOptions {
  /**
   * Сколько РАЗНЫХ исполнителей должны отдать один и тот же сегмент места,
   * чтобы он попал в словарь. Порог именно по числу РАЗНЫХ артистов, а не по
   * сырому числу вхождений: живой прогон показал, что один и тот же
   * исполнитель/лейбл в выдаче топ-хаба повторяется до 4 раз (одна и та же
   * группа с разными релизами) — считать это 4 независимыми
   * подтверждениями было бы неверно, а единственный шуточный/ошибочный
   * `band_location` при таком повторе мог бы набрать вес, которого не
   * заслуживает.
   *
   * 2 — минимальный порог, отличающий систематическое место от случайности:
   * band_location — это структурированное поле профиля группы на Bandcamp
   * (не свободный тег), так что риск, что ДВА разных артиста независимо
   * впишут туда одно и то же нежанровое слово — исчезающе мал. Живая
   * проверка (2026-08, см. отчёт по задаче) на выборке всего 120
   * результатов (2 хаб-тега × 60) уже дала 'richmond, virginia' от 4 разных
   * исполнителей/лейблов, 'philadelphia, pennsylvania' от 3 — при
   * реальном прогоне антипрофиля (несколько хаб-тегов на каждый из 4
   * бакетов, до ~700 сырых результатов) порог 2 отсеивает единичный шум, не
   * теряя настоящие места.
   */
  minDistinctArtists?: number;
}

/** NFD-разложение + вырезание комбинирующих диакритических знаков (U+0300–U+036F). */
function stripDiacritics(value: string): string {
  return value.normalize('NFD').replace(/[\u0300-\u036f]/g, '');
}

/**
 * Один сегмент `band_location` → сопоставимая с тегом строка: нижний
 * регистр, без диакритики ('Montréal' → 'montreal' — совпадает с тем, как
 * этот тег реально записан на Bandcamp, см. 'montreal' в data/profile.json),
 * точки заменены на пробел и схлопнуты ('Washington, D.C.' → сегмент 'd.c.'
 * → 'd c'), обрезаны крайние пробелы.
 */
export function normalizeLocationToken(raw: string): string {
  return stripDiacritics(raw)
    .toLowerCase()
    .replace(/\./g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * `band_location` → нормализованные сегменты через запятую. Живой запрос
 * (2026-08, discover_web, слайс 'top' по 'crust' и 'hardcore-punk',
 * 120 результатов) подтвердил формат: "Город, Регион/Страна"
 * ('Richmond, Virginia', 'Borlänge, Sweden', 'Montréal, Québec') или голое
 * "Регион"/"Страна" без города ('Sweden', 'California', 'New Jersey'), либо
 * пустая строка. Разбиение по запятой даёт ровно ту грануляцию, в которой
 * голый тег-город реально встречается на Bandcamp — 'richmond', 'new york',
 * 'vienna' каждый как ОДИН тег, а не как отдельные слова 'new'+'york'.
 */
export function locationSegments(location: string | null | undefined): string[] {
  if (!location) return [];
  return location
    .split(',')
    .map(normalizeLocationToken)
    .filter((segment) => segment.length > 0);
}

/**
 * Строит словарь мест из харвеста `band_location` — целые нормализованные
 * сегменты ('richmond', 'new york', 'sweden'), не отдельные слова внутри
 * них. Это осознанный выбор гранулярности сопоставления в build.ts: тег
 * там сверяется с этим словарём ЦЕЛИКОМ, а не по словам-токенам внутри тега.
 *
 * Причина — та же коллизия слова и места, которую словарь и должен решать.
 * 'bath', 'nice', 'reading' — обычные английские/французские слова
 * настолько же, насколько и настоящие города: если бы сопоставление резало
 * составной тег на токены и проверяло каждый по отдельности, единственное
 * совпавшее слово внутри многословного тега убивало бы тег целиком по
 * причине, не имеющей отношения к географии (гипотетический тег вроде
 * 'reading room sessions' не место просто потому, что несёт слово
 * 'reading'). Сравнение целого тега с целым сегментом словаря такого не
 * допускает: 'richmond va' или 'boston punk' не совпадут с сегментами
 * 'richmond'/'boston' целиком (это другие строки) и переживут фильтр —
 * ложноотрицательно (эти теги тоже отчасти география), но безопасно;
 * ложноположительный вариант (срезать жанровый сигнал у тега, который лишь
 * СОДЕРЖИТ слово-место) вреднее, а частичные гео-теги — не то, из-за чего
 * 'new york' весит 1 в живом прогоне: там виноваты именно голые
 * тег-города, и по ним сравнение целого тега бьёт точно.
 */
export function buildLocationVocabulary(
  samples: readonly LocationSample[],
  options: LocationVocabularyOptions = {},
): string[] {
  const minDistinctArtists = options.minDistinctArtists ?? 2;
  const artistsBySegment = new Map<string, Set<string>>();

  for (const sample of samples) {
    const artistKey = sample.artist.trim().toLowerCase();
    if (!artistKey) continue; // без имени исполнителя дедуп невозможен — не считаем такой сэмпл
    for (const segment of locationSegments(sample.location)) {
      let artists = artistsBySegment.get(segment);
      if (!artists) {
        artists = new Set();
        artistsBySegment.set(segment, artists);
      }
      artists.add(artistKey);
    }
  }

  return [...artistsBySegment.entries()]
    .filter(([, artists]) => artists.size >= minDistinctArtists)
    .map(([segment]) => segment)
    .sort();
}

/**
 * Формат файла, в который словарь мест пишется на диск (см. bin/build-profile.ts).
 * Плоский отсортированный массив строк — минимальная структура, которую
 * легко просмотреть и вручную поправить (убрать ложное срабатывание,
 * дописать город маленькой DIY-группы, которого не было в хаб-сэмпле).
 */
export interface LocationVocabularyFile {
  generatedAt: string;
  /** Сколько (артист, локация) пар вошли в харвест этого прогона. */
  samplesHarvested: number;
  minDistinctArtists: number;
  locations: string[];
}
