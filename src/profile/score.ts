import type { Candidate } from '../bandcamp/types.ts';
import type { BucketProfile } from './build.ts';
import { canonicalizeTag } from '../lib/tags.ts';

export interface ScoreContext {
  /** Лейбл → вес 0..1 из профиля. */
  labels?: Record<string, number>;
  /** Тег → сколько раз владелец скипнул релиз с этим тегом. */
  tagPenalties?: Record<string, number>;
}

export interface ScoreResult {
  total: number;
  rejected: boolean;
  /**
   * `true`, только если `rejected` случился из-за глобального hard-reject
   * тега (см. аргумент `hardRejectTags` у `score()`) — кандидат не жанрово
   * не дотянул и не попал под стоп-тег бакета, а оказался объектом не того
   * типа (компиляция вместо релиза одного артиста) и был дисквалифицирован
   * безусловно. Всегда `false` при остальных путях отбраковки (ниже
   * MATCH_FLOOR, стоп-тег при слабом совпадении, штрафы за отскипы увели
   * итог в минус) и при успешном проходе — читатель результата не должен
   * путать «не дотянул по вкусу, в другой день может пройти» с «неверный
   * тип объекта, никакой вкус его не спасёт» ни по каким-либо косвенным
   * признакам (например, по total: 0 — оно одинаковое в обоих случаях).
   */
  hardRejected: boolean;
  /**
   * Совпавшие теги по убыванию веса — из них строится строка «почему это
   * тебе». Имеет смысл только при `rejected: false`; при отбраковке всегда
   * `[]` — совпадения были, но релиз всё равно убит стоп-тегом или
   * штрафами, и показывать их как «почему это тебе» было бы враньём.
   */
  reasons: string[];
}

/**
 * Минимальная сумма весов тегов, ниже которой релиз считается чужим.
 *
 * В `build.ts` опорный тег бакета (см. `seedTags` в `./buckets.ts`), если
 * пережил порог `minReleases`, зафиксирован ровно на 0.5 — а не-опорные
 * теги нормализованы к максимуму 1. Значение 0.5 здесь выбрано не
 * произвольно, а впритык под этот факт: релиз, несущий только опорный тег
 * бакета (что верно для КАЖДОГО релиза бакета по построению — см.
 * `bucketsOf`), даёт `tagScore === 0.5` и благодаря строгому неравенству
 * `<` всё ещё проходит порог, а не отбраковывается. Так и задумано в
 * `build.ts`: «релиз с одним лишь общим тегом всё ещё проходит порог
 * совпадения у скорера». Если бы порог оказался выше 0.5, скорер
 * отбраковывал бы вообще все релизы бакета до единого.
 *
 * Сам по себе этот порог не защищает от противоположной ошибки: не-опорные
 * теги нормализуются к максимуму 1, а не 0.5, так что релиз БЕЗ единого
 * жанрового тега бакета может набрать `tagScore >= 0.5` на одних случайных
 * совпадениях (живой прогон, 2026-08: hardcore-punk на `['cleveland',
 * 'diy']` — голая география и общее слово — даёт 0.68 и проходит порог).
 * Поднимать сам MATCH_FLOOR тут не решение — он и так впритык под seed-тег
 * (см. выше), поднять его значило бы сломать этот же инвариант. Решает эту
 * половину не порог суммы, а отдельная проверка `hasSeedTag` ниже —
 * кандидат обязан нести хотя бы один опорный тег бакета, а не просто
 * набрать сумму весов откуда угодно.
 */
const MATCH_FLOOR = 0.5;
/**
 * Совпадение, при котором стоп-тег уже не отбраковывает, а только штрафует.
 *
 * НЕ потолок «один опорный тег + один топовый характерный тег» — это было
 * бы верно, только если бы у бакета никогда не совпадало больше одного
 * опорного тега разом. На практике бакеты держат по несколько опорных
 * тегов (см. `seedTags` в `./buckets.ts`), и КАЖДЫЙ несёт свои 0.5
 * независимо: у hardcore-punk одни голые 'punk' + 'hardcore' + 'hardcore
 * punk' на одном релизе уже дают 1.5 без единого не-опорного тега. 1.5 —
 * это просто порог, начиная с которого совпадение считается «сильным
 * достаточно, чтобы пережить шальной стоп-тег» — набрать его можно и одним
 * опорным плюс топовым характерным тегом (0.5 + 1, тоже частый случай), и
 * несколькими опорными сразу, и любой другой комбинацией с той же суммой.
 * Если релиз настолько точно лёг в профиль, шальной стоп-тег из мусорного
 * тегирования Bandcamp не должен убивать его целиком — только срезать очки.
 */
const STRONG_MATCH = 1.5;
/**
 * Потолок суммарного анти-фидбек штрафа по всем тегам кандидата.
 *
 * Без потолка штраф копится бесконечно и без затухания: 0.25 за каждый
 * скип по каждому тегу. А опорный тег бакета несёт КАЖДЫЙ релиз бакета по
 * построению (см. `bucketsOf`), так что каждый скип наращивает счётчик
 * именно опорного тега — независимо от того, что владелец скипнул. При
 * максимуме позитивного скора около 3 десятка скипов чего угодно из
 * бакета доводят даже идеальное совпадение до нуля, и с этого момента
 * канал отбраковывает всё подряд без шанса на восстановление — при паре
 * скипов в неделю это месяц-два до тихой смерти канала. Потолок в 1
 * оставляет штраф значимым: слабое совпадение он всё ещё топит целиком, но
 * сильное совпадение переживает даже большой обвал по одному тегу.
 */
const FEEDBACK_PENALTY_CAP = 1;

/**
 * `seedTags` — отдельный обязательный аргумент, а не поле `BucketProfile`
 * (которое приходит частично из data/profile.json, а его скорер уже
 * получает как `bucket`). Два кандидата на источник рассматривались:
 *
 * 1. Дописать `seedTags` в `BucketProfile`/data/profile.json. Отклонено:
 *    profile.json хозяин правит руками (см. README), а seedTags — это
 *    код-уровневый источник истины из `./buckets.ts`, не вкусовая настройка.
 *    Раз в файле дублировался бы код, он рано или поздно разойдётся с
 *    `BUCKETS` — а `readJson` в `../lib/state.ts` не валидирует форму
 *    файла против интерфейса: отсутствующее поле молча стало бы
 *    `undefined` в рантайме, и проверка `hasSeedTag` ниже либо упала бы,
 *    либо (что хуже) молча отбраковывала вообще все релизы бакета.
 * 2. Обязательный аргумент `score()` — выбрано. TypeScript требует его на
 *    КАЖДОМ вызове (в отличие от опционального поля `ScoreContext`, которое
 *    можно молча не передать и получить старое поведение без единого
 *    предупреждения) — вызывающий код, забывший его передать, получает
 *    ошибку компиляции, а не тихо изменившееся поведение. `score` при этом
 *    остаётся чистой функцией: результат зависит только от аргументов, без
 *    скрытого чтения `BUCKETS` или чего-либо ещё изнутри модуля.
 */
/**
 * `hardRejectTags` — глобальный (не per-bucket) список тегов, любой из
 * которых убивает кандидата целиком, независимо от того, насколько сильно
 * он иначе совпал с бакетом. Задача, которую решает этот аргумент, — не то
 * же самое, что решает `bucket.stopTags`: стоп-тег бакета маркирует СОСЕДНИЙ
 * ЖАНР, которого хозяин не слушает, и сильное жанровое совпадение по праву
 * должно его пережить (см. `STRONG_MATCH` выше) — это и есть корректное
 * поведение стоп-тега. Компиляция — не соседний жанр и вообще не жанровый
 * сигнал: это неверный ТИП объекта (сборник многих артистов вместо релиза
 * одного), и никакая сила жанрового совпадения не может исправить то, что
 * объект не того типа. Живой прогон (2026-08) показал это прямым текстом:
 * добавление 'compilation' в stopTags конкретного бакета не сработало —
 * компиляция набрала сильное совпадение (штраф стоп-тега срезал только 0.8)
 * и обошла по total настоящий релиз. Отсюда и решение не пытаться "усилить"
 * стоп-тег (поднять штраф, снизить STRONG_MATCH и т.п.) — это сломало бы
 * стоп-тег для его настоящей задачи (сосед по жанру) — а завести отдельный
 * механизм с другой семантикой: полная безусловная отбраковка.
 *
 * Глобальность (один список на весь профиль, не `bucket.hardRejectTags`)
 * тоже осознанный выбор: компиляция — неверный тип объекта для ВСЕХ
 * четырёх каналов разом, а не вкусовая настройка одного из них. Дублировать
 * один и тот же список в четырёх бакетах `data/profile.json` означало бы
 * рано или поздно забыть поправить один из четырёх при правке руками (тот
 * же класс риска дрейфа, что и у `seedTags` выше) — один список на весь
 * `Profile` (см. `Profile.hardRejectTags` в `./build.ts`) структурно
 * исключает эту рассинхронизацию.
 *
 * Обязательный аргумент, а не поле `ScoreContext` — по той же причине, что
 * и `seedTags` двумя абзацами выше: `ScoreContext` можно молча не передать
 * и получить старое поведение без единого предупреждения на компиляции, а
 * забытая защита от компиляций — это не нейтральное "ничего не изменилось",
 * а именно та дыра, ради закрытия которой всё это писалось. TypeScript
 * обязан отловить забытый аргумент на `tsc --noEmit`, а не дать программе
 * тихо начать снова предлагать компиляции.
 */
export function score(
  candidate: Candidate,
  bucket: BucketProfile,
  seedTags: readonly string[],
  hardRejectTags: readonly string[],
  context: ScoreContext,
): ScoreResult {
  const tags = candidate.tags.map((tag) => tag.toLowerCase());

  // Hard-reject проверяется раньше и отдельно от всего остального скоринга
  // ниже (весов тегов, seed-тега, стоп-тегов, штрафов) — см. комментарий у
  // аргумента `hardRejectTags` выше: это не про силу совпадения вообще, а
  // про то, что объект не того типа, поэтому считать вес тегов для него
  // незачем, а тем более незачем позволять ему пройти STRONG_MATCH.
  const hardRejectCanonical = new Set(hardRejectTags.map(canonicalizeTag));
  if (tags.some((tag) => hardRejectCanonical.has(canonicalizeTag(tag)))) {
    // reasons: [] — та же логика, что и у остальных путей отбраковки, см.
    // комментарий на поле в ScoreResult.
    return { total: 0, rejected: true, hardRejected: true, reasons: [] };
  }

  // `bucket.tags`/`bucket.stopTags` приходят из data/profile.json, который
  // хозяин правит руками — он мог вписать туда любое из трёх написаний тега
  // ('crust punk' / 'crust-punk' / 'crustpunk'), а Bandcamp мог тегировать
  // КОНКРЕТНЫЙ релиз иначе, чем написано в профиле. Сравниваем по
  // каноническому ключу (см. `canonicalizeTag` в `../lib/tags.ts`), а не по
  // точной строке — иначе совпадение молча терялось бы всякий раз, когда
  // написания расходятся.
  const weightByCanonicalTag = new Map<string, number>();
  for (const [tag, weight] of Object.entries(bucket.tags)) {
    const key = canonicalizeTag(tag);
    // Если профиль (руками) содержит два написания одного тега — берём
    // большее, а не складываем: это по-прежнему ОДИН тег, суммирование
    // задвоило бы сигнал совпадения без всякого основания.
    const existing = weightByCanonicalTag.get(key);
    if (existing === undefined || weight > existing) weightByCanonicalTag.set(key, weight);
  }
  const stopTagsCanonical = new Set(bucket.stopTags.map(canonicalizeTag));
  const seedTagsCanonical = new Set(seedTags.map(canonicalizeTag));

  const matched = tags
    .map((tag) => ({ tag, weight: weightByCanonicalTag.get(canonicalizeTag(tag)) ?? 0 }))
    .filter((entry) => entry.weight > 0)
    .sort((a, b) => b.weight - a.weight);
  const tagScore = matched.reduce((sum, entry) => sum + entry.weight, 0);

  // Симметрия с профилем: buildProfile засчитывает релиз владельца в
  // бакет, только если тот несёт опорный тег (см. `bucketsOf`) — ни один
  // релиз бакета не может существовать без него. Кандидат обязан
  // соответствовать тому же стандарту, а не только сумме весов: без этой
  // проверки не-опорные теги, нормализованные к максимуму 1, дают релизу
  // без единого жанрового маркера бакета набрать `tagScore >= MATCH_FLOOR`
  // на чистой случайности (живой прогон, 2026-08: hardcore-punk на
  // `['cleveland', 'diy']` — география плюс общее слово — 0.68, проходило
  // порог). MATCH_FLOOR при этом остаётся прежним (0.5) — поднимать его
  // сломало бы задокументированный инвариант «релиз с одним лишь опорным
  // тегом всё ещё проходит порог», см. комментарий на MATCH_FLOOR.
  const hasSeedTag = tags.some((tag) => seedTagsCanonical.has(canonicalizeTag(tag)));

  const stopHits = tags.filter((tag) => stopTagsCanonical.has(canonicalizeTag(tag))).length;
  if (!hasSeedTag || tagScore < MATCH_FLOOR || (stopHits > 0 && tagScore < STRONG_MATCH)) {
    // reasons: [] — см. комментарий на поле в ScoreResult: при отбраковке
    // совпавшие теги не годятся в «почему это тебе». hardRejected: false —
    // это отбраковка по вкусу/жанру, не по типу объекта.
    return { total: 0, rejected: true, hardRejected: false, reasons: [] };
  }

  const labelKey = candidate.label?.trim().toLowerCase() ?? '';
  const labelBonus = 0.7 * (context.labels?.[labelKey] ?? 0);
  // Бонуса за популярность здесь нет намеренно. `alsoCollected` заполняется
  // только у позиций из коллекции самого владельца (fan.ts), а кандидаты
  // приходят из Discover и из коллекций соседей — обе ветки (fresh.ts,
  // archive.ts) проставляют туда 0, потому что взять число неоткуда:
  // ни ответ Discover, ни ld+json страницы релиза его не содержат. Раньше
  // здесь стоял логарифмический член от этого поля — он всегда давал ровно
  // ноль, то есть был мёртвой веткой скоринга с комментарием, описывающим
  // поведение, которого нет. Если популярность когда-нибудь понадобится,
  // сначала нужно найти, откуда её брать, и только потом возвращать член.
  const stopPenalty = 0.8 * stopHits;
  const feedbackPenalty = Math.min(
    FEEDBACK_PENALTY_CAP,
    tags.reduce((sum, tag) => sum + 0.25 * (context.tagPenalties?.[tag] ?? 0), 0),
  );

  const total = tagScore + labelBonus - stopPenalty - feedbackPenalty;
  const rejected = total <= 0;
  return {
    // Обе ветки отбраковки репортят total: 0 — форма результата не должна
    // зависеть от того, КАКОЙ порог сработал (совпадение тегов или штрафы
    // увели итог в минус). Иначе читатель/логгер результата вынужден сам
    // разбираться, что означает отрицательное число рядом с rejected: true.
    total: rejected ? 0 : Number(total.toFixed(3)),
    rejected,
    // Эта ветка отбраковывает по штрафам/сумме весов, никогда по
    // hardRejectTags (та проверка уже вернулась раньше) — hardRejected
    // всегда false здесь, в том числе когда rejected true.
    hardRejected: false,
    reasons: rejected ? [] : matched.map((entry) => entry.tag),
  };
}
