/**
 * cyrb53 — компактный детерминированный строковый хеш без зависимостей,
 * даёт 53-битное число (весь безопасный диапазон `Number` в JS).
 *
 * Общая точка для всех мест пайплайна, которым нужен стабильный числовой id
 * для релиза, у которого нет настоящего числового `item_id` от Bandcamp (или
 * который сознательно не хранится, чтобы не дублировать данные) — itemId в
 * `Candidate` используется как ключ дедупликации «уже показано» и как
 * содержимое callback_data телеграм-кнопок, по которому нажатие
 * сопоставляется с конкретной карточкой. Присвоить всем такой itemId: 0 —
 * значит слить их все в одну запись при дедупе и сделать нажатие кнопки на
 * любой из них неотличимым от нажатия на любую другую. Хеш URL детерминирован
 * (один и тот же релиз в разных прогонах и из разных источников получает
 * один и тот же id) и с исчезающе малой вероятностью коллизий на объёмах,
 * которые видит один канал.
 *
 * Используется:
 * - `src/pipeline/fresh.ts` — для релизов, найденных через дискографию
 *   группы/лейбла (у страницы /music числового item_id нет).
 * - `src/pipeline/archive.ts` — для архивных кандидатов: itemId соседского
 *   релиза в `data/neighbors.json` не хранится (см. `NeighborItem`-историю в
 *   `src/pipeline/neighbors.ts`), он всё равно был лишь удобной ручкой для
 *   callback_data, а не ключом дедупликации (та идёт по URL).
 */
export function hashUrl(url: string): number {
  let h1 = 0xdeadbeef;
  let h2 = 0x41c6ce57;
  for (let i = 0; i < url.length; i++) {
    const ch = url.charCodeAt(i);
    h1 = Math.imul(h1 ^ ch, 2654435761);
    h2 = Math.imul(h2 ^ ch, 1597334677);
  }
  h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507) ^ Math.imul(h2 ^ (h2 >>> 13), 3266489909);
  h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507) ^ Math.imul(h1 ^ (h1 >>> 13), 3266489909);
  return 4294967296 * (2097151 & h2) + (h1 >>> 0);
}
