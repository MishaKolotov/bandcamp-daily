/**
 * Единая точка СРАВНЕНИЯ тегов по всему проекту — теги, лежащие в основе
 * бакетов (`src/profile/buckets.ts`), профиля вкуса (`src/profile/build.ts`),
 * скоринга (`src/profile/score.ts`) и антипрофиля (`src/profile/stop-tags.ts`),
 * приходят с Bandcamp написанными по-разному: пробелом, дефисом или слитно
 * ('crust punk' / 'crust-punk' / 'crustpunk', 'd-beat' / 'dbeat' / 'd beat').
 * Хозяин явно потребовал считать их одним и тем же тегом — эта функция и
 * есть то единственное место, которое решает, совпадают ли два написания.
 *
 * ГДЕ это применяется: только в местах СРАВНЕНИЯ/ГРУППИРОВКИ (bucketsOf,
 * аккумулятор весов в buildProfile, поиск веса в score, пул хаб-тегов в
 * deriveStopTags). Страница релиза (`src/bandcamp/album.ts`) — граница, на
 * которой теги входят в систему — этой функцией НЕ проходит: она отдаёт тег
 * ровно так, как его показывает Bandcamp (только нижний регистр и trim, без
 * малейшего изменения формы). Так `data/profile.json` (который хозяин правит
 * руками) и текст карточек в Telegram остаются человекочитаемыми — 'crust
 * punk', а не 'crustpunk' — при этом СРАВНЕНИЕ двух тегов из разных мест
 * всё равно идёт по одному правилу, потому что все места сравнения зовут
 * именно эту функцию, а не пишут своё сравнение по месту.
 *
 * ПРАВИЛО: нижний регистр, trim, все пробелы и дефисы (включая повторы и
 * смесь вроде "d -  beat") вырезаются целиком, остальные символы не трогаем.
 * Вырезать ТОЛЬКО пробел/дефис, а не любую пунктуацию — осознанный выбор:
 * 'r&b' должен остаться 'r&b', а не схлопнуться с каким-то не связанным по
 * смыслу тегом только потому, что оба содержат один и тот же случайный
 * небуквенный символ. Пробел и дефис — единственные два разделителя, которые
 * реально встречаются как альтернативные написания ОДНОГО тега в этом домене
 * (см. `d-beat`/`crust punk` в задаче) — амперсанд, точки, апострофы такого
 * применения не имеют и целенаправленно не трогаются.
 *
 * Проверено на потенциальные ложные схлопывания по этому домену: 'post-punk'
 * и 'post punk' — уже сегодня один и тот же жанр под двумя написаниями
 * (слияние верное); голое 'hardcore' НЕ пересекается с 'hardcore punk'
 * (разное количество слов после вырезания разделителя — 'hardcore' vs
 * 'hardcorepunk', разные строки), что важно: `buckets.ts` намеренно держит
 * голый 'hardcore' как отдельный омонимный сигнал от составного 'hardcore
 * punk' — canonicalizeTag не имеет права их перепутать, и не путает.
 */
export function canonicalizeTag(tag: string): string {
  return tag.trim().toLowerCase().replace(/[\s-]+/g, '');
}

/**
 * Несколько сырых написаний одного канонического тега ('d-beat', 'dbeat',
 * 'd beat') после схлопывания всё ещё нужно ПОКАЗАТЬ человеку одним
 * написанием — в `data/profile.json` и в карточках. `counts` — написание →
 * сколько раз оно встретилось (в релизах бакета, в сэмпле хаба и т.п.).
 *
 * Правило: побеждает написание, встретившееся чаще всего — это и есть то,
 * как тег реально пишут на Bandcamp и как его набирает сам хозяин, а не
 * произвольно выбранная "более читаемая" форма. При равном счёте — то,
 * что было замечено раньше (`Map` перебирается в порядке вставки, а вызывающий
 * код добавляет написания в порядке обработки данных) — детерминировано без
 * дополнительной догадки о читаемости.
 */
export function pickDisplaySpelling(counts: ReadonlyMap<string, number>): string {
  let best: string | undefined;
  let bestCount = -Infinity;
  for (const [spelling, count] of counts) {
    if (count > bestCount) {
      best = spelling;
      bestCount = count;
    }
  }
  if (best === undefined) {
    throw new Error('pickDisplaySpelling: пустой набор написаний — вызывающий код завёл группу без содержимого');
  }
  return best;
}
