import type { BucketId, Candidate } from '../bandcamp/types.ts';
import type { BucketProfile } from '../profile/build.ts';
import { score, type ScoreContext } from '../profile/score.ts';

/**
 * Входные данные одного бакета для сквозного рейтинга. По форме — то же
 * самое, что раньше уходило в `SelectOptions` (`../pipeline/select.ts`) по
 * одному бакету за вызов, только `pickBest` ниже принимает СРАЗУ массив
 * таких входов: раньше на каждый бакет был свой канал и свой независимый
 * вызов `selectForBucket`, теперь каналов нет — один заход отдаёт ровно
 * одного победителя среди кандидатов ВСЕХ бакетов разом, а значит и
 * скорить их нужно в одном месте, чтобы честно сравнивать `total` между
 * жанрами (см. большой комментарий у `pickBest` ниже, почему это вообще
 * законно).
 */
export interface BucketInput {
  id: BucketId;
  profile: BucketProfile;
  /**
   * Опорные теги бакета (см. `seedTags` в `../profile/buckets.ts`) —
   * прокидываются насквозь в `score()`, который требует хотя бы один из них
   * у любого кандидата (см. `hasSeedTag` в `../profile/score.ts`). Как и в
   * `SelectOptions`, поле обязательное, а не опциональное, по той же
   * причине: `score()` сам требует его обязательным аргументом, забытое
   * поле обязано ронять компиляцию, а не тихо менять поведение.
   */
  seedTags: readonly string[];
  fresh: Candidate[];
  archive: Candidate[];
}

export interface PickOptions {
  buckets: BucketInput[];
  /**
   * Глобальный (не per-bucket) список hard-reject тегов — см.
   * `hardRejectTags` у `score()` в `../profile/score.ts`. Один список на все
   * бакеты разом: причина та же, что и у `Profile.hardRejectTags` в
   * `../profile/build.ts` — компиляция не тип объекта, зависящий от жанра, а
   * значит и отбраковывать её нужно одинаково во всех бакетах.
   */
  hardRejectTags: readonly string[];
  /**
   * URL релизов, уже показанных владельцу. Ключ — URL, а не itemId (та же
   * причина, что и у снятого вместе с каналами `selectForBucket`: itemId
   * не сравним между источниками, детерминированный ключ между fresh.ts,
   * archive.ts и этой функцией — только URL).
   */
  seen: ReadonlySet<string>;
  context: ScoreContext;
  alternativesCount: number;
  /**
   * Порог отсечения по итоговому `total` победителя. В отличие от
   * `MATCH_FLOOR`/`STRONG_MATCH` внутри `score()` (те решают, годится ли
   * кандидат бакету ВООБЩЕ), этот порог — решение более высокого уровня:
   * «даже лучший из всех подошедших кандидатов настолько слаб, что лучше
   * прислать владельцу ничего, чем это». `score()` сам по себе такого
   * решения принять не может — он не видит остальных кандидатов и не знает,
   * что этот заход вообще может остаться без победителя.
   */
  minTotal: number;
  /**
   * Бакет, из которого был предыдущий пик. Опционален: до первого захода
   * прошлого пика ещё не было. Назначение — не жанровое разнообразие само
   * по себе (это решала бы нормировка), а конкретно «не прислать один и тот
   * же жанр два раза подряд» — см. развёрнутое обоснование у `pickBest`.
   */
  excludeBucket?: BucketId;
}

/** Итог отбора одного кандидата внутри бакета — то же самое, что раньше строил `rankPool` в `./select.ts`, но с меткой бакета-владельца. */
interface RankedEntry {
  bucket: BucketId;
  candidate: Candidate;
  matchedTags: string[];
  total: number;
}

export interface BestPick {
  bucket: BucketId;
  candidate: Candidate;
  matchedTags: string[];
  total: number;
  /**
   * Следующие по скору кандидаты ТОГО ЖЕ бакета, что и победитель — не более
   * `alternativesCount`. Только бакет победителя, а не любые оставшиеся
   * кандидаты вообще: карточка уходит на сайт вместе с жанром победителя
   * (`bucket` и `bucketTitle` в теле `POST /api/picker/pick`), жанр печатается
   * в подписи и остаётся в строке `picker_pending` неизменным. Кнопка «Другой»
   * подменяет на сайте только кандидата, а подпись перерисовывается с тем же
   * `bucket_title` — подсунь ей релиз чужого бакета, и на карточке был бы
   * написан один жанр, а показан другой. Короче: смена кандидата кнопкой
   * «Другой» обязана быть заменой ТОЛЬКО музыки, а не жанра карточки.
   */
  alternatives: Candidate[];
}

/**
 * Схлопывает кандидатов, отранжированных по РАЗНЫМ бакетам, по URL.
 *
 * Один и тот же релиз законно проходит скоринг сразу нескольких бакетов —
 * это не баг источника данных, а обычный кроссовер (crust/hardcore-punk,
 * atmospheric black metal/post-black и т.п.: релиз несёт опорные теги сразу
 * двух жанров, `bucketsOf` в `../profile/buckets.ts` от этого и заводит
 * запись сразу в оба бакета при построении профиля). Показать владельцу его
 * дважды под двумя разными карточками бессмысленно — вопрос не «показывать
 * или нет», а «чей он больше»: `total` для одного и того же кандидата в
 * разных бакетах, как правило, разный (разный набор весов тегов), и большее
 * значение и есть более точный ответ на вопрос, к какому жанру релиз ближе
 * по вкусу владельца.
 *
 * При точном равенстве `total` (оба бакета оценили релиз одинаково сильно)
 * решает меньший по алфавиту id бакета. Сам по себе он ничего не значит —
 * просто способ сделать исход детерминированным независимо от порядка
 * обхода `options.buckets`, ровно то же соображение, что и у вторичного
 * ключа сортировки в `rankPool` (`./select.ts`).
 */
function dedupeAcrossBuckets(entries: RankedEntry[]): RankedEntry[] {
  const byUrl = new Map<string, RankedEntry>();
  for (const entry of entries) {
    const existing = byUrl.get(entry.candidate.url);
    const wins =
      !existing || entry.total > existing.total || (entry.total === existing.total && entry.bucket < existing.bucket);
    if (wins) byUrl.set(entry.candidate.url, entry);
  }
  return [...byUrl.values()];
}

/**
 * Сквозной рейтинг кандидатов всех бакетов разом — замена `selectForBucket`
 * (`./select.ts`) под мир без четырёх каналов. Раньше у каждого бакета был
 * свой канал, и «лучший в бакете» само по себе было финальным ответом; теперь
 * личка владельца одна, и вопрос всегда «лучший из ЛЮБОГО бакета».
 *
 * ПОЧЕМУ ЗАКОННО СРАВНИВАТЬ raw `total` РАЗНЫХ БАКЕТОВ НАПРЯМУЮ, без
 * нормировки: шкала весов у всех бакетов общая по построению `buildProfile`
 * (`../profile/build.ts`) — опорный тег бакета, если пережил
 * `minReleases`, зафиксирован ровно на 0.5, а любой другой тег нормирован
 * относительным `normalize()` к максимуму РОВНО 1 (см. комментарий в
 * `buildProfile` у присвоения `nonSeedScores`/`normalizedByKey`). Это не
 * совпадение и не допущение с нашей стороны, а инвариант, который
 * поддерживает сам `build.ts`: любой бакет, каким бы дискриминирующим тегом
 * он ни описывался, кладёт свои веса тегов в диапазон [0, 1] (не-опорные) с
 * фиксированной точкой 0.5 у опорного. Раз шкала одна и та же у всех
 * бакетов, `total` (сумма весов совпавших тегов плюс бонус лейбла минус
 * штрафы, см. `score()` в `../profile/score.ts`) одного бакета сравним с
 * `total` другого без всякого пересчёта — складывать кандидатов разных
 * жанров в один список и сортировать по `total` законно ровно потому, что
 * единица измерения этого числа одна и та же независимо от бакета.
 *
 * ЧТО ЭТО НЕ РЕШАЕТ: плотнее населённый бакетом жанр (у владельца в
 * коллекции сильно больше краста, чем блэк-метала, скажем) статистически
 * будет предлагать более специфичные/тяжёлые по весам совпадения просто
 * потому, что там больше материала для over-representation в `build.ts` —
 * и в сыром сравнении `total` он будет выигрывать чаще, честно отражая
 * структуру коллекции, а не какую-то ошибку скоринга. Лечить это
 * нормировкой (поделить `total` каждого бакета на что-то вроде среднего по
 * бакету) значило бы испортить сам инвариант, который делает сравнение
 * законным: нормировка ушла бы от объективной силы совпадения к
 * искусственному "по одному из каждого жанра" — то есть откатила бы систему
 * обратно к бакетному отбору, который эта задача как раз убирает. Настоящий
 * инструмент для перекоса — `excludeBucket`: если прошлый заход уже выбрал
 * из плотного жанра, следующий заход исключает этот бакет целиком и честно
 * даёт слово остальным, вместо того чтобы подрезать всем шкалу.
 *
 * Функция чистая: ни сети, ни файлов, ни чтения глобальных переменных —
 * результат зависит только от аргументов.
 */
export function pickBest(options: PickOptions): BestPick | null {
  const entries: RankedEntry[] = [];
  for (const bucket of options.buckets) {
    // Бакет прошлого пика пропускается ЦЕЛИКОМ, а не просто штрафуется —
    // см. обоснование `excludeBucket` в JSDoc выше и на самом поле.
    if (bucket.id === options.excludeBucket) continue;

    // fresh и archive внутри бакета — один пул на рассмотрение: разница
    // между ними («вышло сегодня» вместо «откопано у соседей») важна для
    // текста карточки (`why()` в подписи на стороне сайта), но не для того,
    // какой релиз сильнее совпал со вкусом — обе ветки проходят один и тот
    // же скоринг на равных.
    for (const candidate of [...bucket.fresh, ...bucket.archive]) {
      if (options.seen.has(candidate.url)) continue;
      const result = score(candidate, bucket.profile, bucket.seedTags, options.hardRejectTags, options.context);
      if (result.rejected) continue;
      entries.push({ bucket: bucket.id, candidate, matchedTags: result.reasons, total: result.total });
    }
  }

  const deduped = dedupeAcrossBuckets(entries);

  // Тот же вторичный ключ, что был и у снятого `rankPool`, и по той же
  // причине: равный `total` — не редкость (несколько кандидатов совпали с
  // одним и тем же набором тегов бакета), а порядок кандидатов на входе не
  // гарантирован между прогонами. URL как строка ничего не значит сам по
  // себе, но стабилен и есть у каждого кандидата — результат перестаёт
  // зависеть от порядка `options.buckets` и порядка `fresh`/`archive` внутри
  // них.
  deduped.sort((a, b) => {
    if (b.total !== a.total) return b.total - a.total;
    return a.candidate.url < b.candidate.url ? -1 : a.candidate.url > b.candidate.url ? 1 : 0;
  });

  const top = deduped[0];
  // Нет ни одного прошедшего скоринг кандидата ИЛИ даже лучший из них не
  // дотягивает до minTotal — в обоих случаях ответ один: в этот заход
  // прислать нечего, лучше промолчать, чем прислать заведомо мимо вкуса.
  if (!top || top.total < options.minTotal) return null;

  const alternatives = deduped
    .slice(1)
    // Только бакет победителя — см. развёрнутое обоснование в JSDoc на
    // `BestPick.alternatives`: подмена кандидата кнопкой «другой» на релиз
    // чужого жанра разошлась бы и с подписью карточки, и с тем, как
    // `handleUpdates` ищет карточку в `pending` по бакету.
    .filter((entry) => entry.bucket === top.bucket)
    // Порог держит и запас тоже. Кандидат ниже `minTotal` — это ровно то, о
    // чём подборщик сам решил бы «лучше промолчать»; выдать его по нажатию
    // «другой» значило бы обойти собственное решение через кнопку. Молчание
    // здесь честнее: кончившийся запас закрывает карточку и говорит об этом
    // прямо, а проходняк под видом второго варианта — нет.
    .filter((entry) => entry.total >= options.minTotal)
    .slice(0, options.alternativesCount)
    .map((entry) => entry.candidate);

  return { bucket: top.bucket, candidate: top.candidate, matchedTags: top.matchedTags, total: top.total, alternatives };
}
